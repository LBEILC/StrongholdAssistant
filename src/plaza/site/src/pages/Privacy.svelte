  <h1>隐私说明</h1>
  <p class="muted">更新于 2026 年 11 月 12 日</p>

  <p>阵容广场是卫戍协议助手的配套网站，由个人开发者非商业运营，托管在 Cloudflare。下面说明我们收集什么、怎么用、怎么删。</p>

  <h2>我们收集的</h2>
  <ul>
    <li><b>邮箱</b>：用来发送登录验证码。只有你本人能在「我的」里看到打码后的邮箱，不会公开，也不会用来发广告。</li>
    <li><b>昵称</b>：显示在你发布的阵容上，是公开的。</li>
    <li><b>你发布的阵容和简介、你的点赞</b>：阵容和简介是公开的；点赞只显示总数。</li>
    <li><b>导入计数用的设备标识</b>：复制分享码时，浏览器或助手里随机生成的一串 id，只存它的哈希，用来避免同一台设备重复计数。</li>
    <li><b>登录凭据</b>：浏览器里一个 30 天有效的 Cookie，只用来保持登录。</li>
    <li><b>IP 地址</b>：只在发送验证码时记录，用来限制发送频率、防止滥用。</li>
  </ul>

  <h2>第三方服务</h2>
  <ul>
    <li><b>Cloudflare</b>：托管网站和数据库，并提供人机验证（Turnstile）。</li>
    <li><b>Resend</b>：发送验证码邮件，会处理你的邮箱地址。</li>
  </ul>
  <p>除此之外不会把你的数据提供给任何人。</p>

  <h2>删除</h2>
  <p>在「我的」页面可以随时注销账号：你的邮箱、昵称、发布的所有阵容和点赞会被删除，不能恢复。</p>

  <h2>内容规范</h2>
  <p>阵容发布后立即公开。广告、引流、违法或冒犯性的内容会被下架，严重的会封禁账号。</p>

  <h2>和游戏的关系</h2>
  <p>这是非官方的粉丝项目，与上海鹰角网络无关。游戏美术、角色名称与数据归上海鹰角网络所有。</p>
